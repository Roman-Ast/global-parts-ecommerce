<?php

namespace App\Console\Commands\Ozon;

/**
 * Комиссии Ozon по типам товаров.
 *
 * ИСТОРИЯ: Роман усомнился в 47% ещё 2026-09-03 ("что-то слишком
 * нереально") — и оказался прав, хоть цифра и была честной для СТАРОГО
 * договора (ООО «Интернет Решения», российское юрлицо). 2026-09-16,
 * после перехода на договор ОМК (ТОО «Озон Маркетплейс Казахстан») и
 * переноса карточек в новый кабинет — живой запрос тем же способом
 * (/v3/product/info/list → commissions[], артикул LYNXauto-CD1246,
 * новый Client-Id) показал: **percent=10 (FBO) / 12 (FBS)**, и —
 * важно — **currency_code: "KZT"**, не RUB. Используем FBS-ставку (12%),
 * т.к. работаем через собственный FBS-склад, тем же принципом, что и
 * раньше со старым договором.
 *
 * Курс KZT→RUB (EXCHANGE_RATE_KZT_TO_RUB) с переходом на ОМК БОЛЬШЕ НЕ
 * НУЖЕН — цены на новом договоре нативно в тенге, конвертация убрана из
 * OzonPriceCalculator целиком. Константа оставлена только как исторический
 * след на случай отката на старый договор — нигде не используется.
 */
class OzonCommissionRates
{
    /** @deprecated Не используется с перехода на договор ОМК (2026-09-16) — цены нативно в KZT. */
    public const EXCHANGE_RATE_KZT_TO_RUB = 0.19;

    /**
     * FBS-ставка по договору ОМК — подтверждено живьём 2026-09-16 на
     * реальной перенесённой карточке. FBO там же — 10%, но мы работаем
     * через собственный FBS-склад.
     */
    public const DEFAULT_COMMISSION_PERCENT = 12.0;

    /**
     * По ozon type_id — переопределения ставки для конкретных типов
     * товаров, когда Роман подтвердит реальные цифры (сейчас пусто,
     * всё падает на DEFAULT_COMMISSION_PERCENT).
     *
     * @var array<int, float>
     */
    public const BY_TYPE_ID = [
        // 970744063 => 47.0, // Амортизатор подвески — подтвердить
    ];

    public static function forType(int $typeId): float
    {
        return self::BY_TYPE_ID[$typeId] ?? self::DEFAULT_COMMISSION_PERCENT;
    }
}
