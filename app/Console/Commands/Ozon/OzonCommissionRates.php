<?php

namespace App\Console\Commands\Ozon;

/**
 * Комиссии Ozon по типам товаров — константы-заглушки, требуют сверки
 * (Роман 2026-09-03: "47% что-то слишком нереально", запросил уточнить).
 * Единственная РЕАЛЬНО измеренная живьём цифра — 47% для "Амортизатор
 * подвески" (type_id=970744063) на одной тестовой карточке
 * (/v3/product/info/list → commissions[].percent, price=3500 RUB, все схемы
 * FBO/FBS/RFBS/FBP одинаковы). Второй тестовый прогон на другой цене не
 * дал чистых данных — карточка не прошла из-за конфликта группировки
 * вариантов (одинаковое "Название модели" у двух offer_id), поэтому пока
 * НЕ подтверждено, зависит ли % от цены или это чистая ставка категории.
 *
 * Курс KZT→RUB — тоже заглушка, не привязана к живому курсу ЦБ/биржи.
 */
class OzonCommissionRates
{
    /** Не проверено на живом курсе — ориентировочно, поправить перед боевым запуском. */
    public const EXCHANGE_RATE_KZT_TO_RUB = 0.19;

    /** Единственная измеренная живьём ставка (см. докблок выше) — под вопросом. */
    public const DEFAULT_COMMISSION_PERCENT = 47.0;

    /**
     * По ozon type_id — переопределения ставки для конкретных типов
     * товаров, когда Роман подтвердит реальные цифры (сейчас пусто,
     * всё падает на DEFAULT_COMMISSION_PERCENT).
     *
     * @var array<int, float>
     */
    public const BY_TYPE_ID = [
        // 970744063 => 47.0, // Амортизатор подвески — подтвердить
    ];

    public static function forType(int $typeId): float
    {
        return self::BY_TYPE_ID[$typeId] ?? self::DEFAULT_COMMISSION_PERCENT;
    }
}
